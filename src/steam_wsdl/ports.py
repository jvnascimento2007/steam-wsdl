"""Presentation boundary. Descriptions and messages are plain text."""
from typing import Protocol
from .models import DownloadJob


class Observer(Protocol):
    def add_task(self, description: str, *, total: int | None = None, start: bool = True) -> int: ...
    def update(self, task: int, *, total: int | None = None, completed: int | None = None,
               advance: int | None = None, description: str | None = None) -> None: ...
    def start_task(self, task: int) -> None: ...
    def remove_task(self, task: int) -> None: ...
    def message(self, text: str) -> None: ...
    def completed(self, job: DownloadJob) -> None: ...
